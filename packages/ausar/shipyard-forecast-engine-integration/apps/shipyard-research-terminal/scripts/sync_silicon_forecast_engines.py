#!/usr/bin/env python3
"""Export the pinned Silicon forecast contracts and scorer parity vectors."""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from dataclasses import asdict
from pathlib import Path


def sample_value(engine_index: int, feature_index: int, feature: dict[str, object]) -> float:
    value_range = feature.get("value_range")
    if value_range is not None:
        low, high = value_range
        fraction = 0.35 + 0.05 * ((engine_index + feature_index) % 5)
        return float(low) + (float(high) - float(low)) * fraction

    name = str(feature["name"])
    unit = str(feature["unit"])
    if "days_to_" in name:
        return 5.0
    if "staleness" in name:
        return 0.2
    if any(token in name for token in ("confidence", "quality", "breadth", "acceptance", "coverage", "reliability")):
        return 0.65
    if unit == "ratio":
        return 0.45
    if unit == "signed_ratio":
        return -0.25
    if unit == "beta":
        return 0.7
    if unit in {"z", "signed_z"} or name.endswith("_z"):
        return 0.15 * (((engine_index * 3 + feature_index) % 9) - 4)
    return 0.7


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("silicon_root", type=Path)
    args = parser.parse_args()
    silicon_root = args.silicon_root.resolve()
    if not (silicon_root / "research" / "forecast_engines" / "catalog.py").is_file():
        raise SystemExit("silicon_root must point to the Silicon repository.")
    sys.path.insert(0, str(silicon_root))
    from research.forecast_engines.catalog import ENGINES
    from research.forecast_engines.scorers import score

    commit = subprocess.check_output(
        ["git", "rev-parse", "HEAD"], cwd=silicon_root, text=True
    ).strip()
    if len(commit) != 40 or any(char not in "0123456789abcdef" for char in commit):
        raise SystemExit("Could not determine the exact Silicon source commit.")

    site_root = Path(__file__).resolve().parents[1]
    source = {
        "repository": "https://github.com/dwj9ddyvf6-hub/Silicon",
        "commit": commit,
        "path": "research/forecast_engines",
    }
    catalog = [asdict(engine) for engine in ENGINES]
    catalog_source = (
        "// Generated by scripts/sync_silicon_forecast_engines.py; do not edit by hand.\n"
        f"export const SILICON_FORECAST_SOURCE = Object.freeze({json.dumps(source, ensure_ascii=False, indent=2)});\n"
        f"export const FORECAST_ENGINE_CATALOG = Object.freeze({json.dumps(catalog, ensure_ascii=False, indent=2, allow_nan=False)});\n"
    )
    (site_root / "dist" / "forecast-engine-catalog.mjs").write_text(
        catalog_source, encoding="utf-8", newline="\n"
    )

    parity = []
    for engine_index, engine in enumerate(ENGINES):
        features = {
            item.name: sample_value(engine_index, feature_index, asdict(item))
            for feature_index, item in enumerate(engine.inputs)
        }
        signal = score(engine.formula, features)
        parity.append({
            "engine_id": engine.engine_id,
            "features": features,
            "expected": {
                "value": signal.value,
                "model_score": signal.model_score,
                "drivers": dict(signal.drivers),
            },
        })
    (site_root / "tests" / "fixtures" / "forecast-engine-golden.json").write_text(
        json.dumps({"source": source, "engines": parity}, ensure_ascii=False, indent=2, allow_nan=False) + "\n",
        encoding="utf-8",
        newline="\n",
    )

    print(json.dumps({"source_commit": commit, "engine_count": len(catalog), "golden_cases": len(parity)}))


if __name__ == "__main__":
    main()
