#!/usr/bin/env python3
"""Generate site/live.js, the browser live layer, from INFO-MAP.md.

The cadence class of every hub page is the one INFO-MAP.md assigns it
(its own inputs decide how fast it can honestly move). This generator
reads that table and bakes the map into live.js, so the served poll
cadence can never drift from the audited contract: regenerate with

    python3 build_live_js.py

Fail direction: a hub slug with no INFO-MAP row, or a cadence class
outside the known set, fails the build loudly.
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
INFO_MAP = (HERE.parents[1] / "research_notes" /
            "terminal-visual-expression-20261031" / "INFO-MAP.md")
KNOWN = {"intraday-minutes", "daily-close", "weekly", "static-study"}

TEMPLATE = r"""/* Live layer: polite auto-refresh by cadence class.
   GENERATED by build_live_js.py from INFO-MAP.md - do not hand edit.
   A page polls only its own data file, cache-free, on the cadence its
   own inputs arrive at. When the file changes, the page re-renders in
   place and its top bar clock advances. Nothing here invents data:
   the clock reads the served file's own Last-Modified stamp. */
(function () {
  "use strict";
  var CADENCE = __CADENCE__;
  var POLL_MS = { "intraday-minutes": 180000, "daily-close": 3600000,
                  "weekly": 3600000, "static-study": 0 };
  var STALE_MS = { "intraday-minutes": 1200000, "daily-close": 108000000,
                   "weekly": 777600000, "static-study": Infinity };
  var parts = window.location.pathname.split("/").filter(Boolean);
  var si = parts.lastIndexOf("site"); if (si >= 0) parts = parts.slice(si + 1);
  if (parts.length && parts[parts.length - 1] === "index.html") parts.pop();
  var slug = parts.length ? parts[parts.length - 1] : "";
  var onHub = parts.length === 0;
  var cadence = onHub ? "daily-close" : CADENCE[slug];
  if (!onHub && !cadence) return; // desk copy and off-hub pages: not ours
  var NODATA = __NODATA__;
  /* The hub's own stamp is lane_state.json: every lane close rewrites
     it, while the hub page file only changes when a card changes. */
  var dataUrl = onHub ? "lane_state.json" : (NODATA[slug] ? "index.html" : "data.json");
  var qs = new URLSearchParams(window.location.search);
  var pollMs = POLL_MS[cadence];
  var override = parseInt(qs.get("livepoll") || "", 10);
  if (override >= 2) pollMs = override * 1000; // operator/test override
  var fingerprint = null, updatedAt = null, updates = 0;

  function etNow() {
    try {
      var f = new Intl.DateTimeFormat("en-US", { timeZone: "America/New_York",
        weekday: "short", hour: "2-digit", minute: "2-digit", hour12: false });
      var bag = {};
      f.formatToParts(new Date()).forEach(function (p) { bag[p.type] = p.value; });
      var mins = parseInt(bag.hour, 10) * 60 + parseInt(bag.minute, 10);
      var weekday = ["Mon", "Tue", "Wed", "Thu", "Fri"].indexOf(bag.weekday) >= 0;
      return { marketOpen: weekday && mins >= 570 && mins < 960 };
    } catch (e) { return { marketOpen: true }; }
  }
  function fmtClock(d) {
    if (!d) return "";
    return d.toLocaleTimeString("en-GB", { hour12: false });
  }
  function indicator() {
    var bar = document.querySelector(".topbar");
    if (!bar) return null;
    var ind = bar.querySelector(".liveind");
    if (!ind) {
      ind = document.createElement("span"); ind.className = "liveind";
      var dot = document.createElement("span"); dot.className = "livedot";
      var txt = document.createElement("span"); txt.className = "livetext";
      ind.appendChild(dot); ind.appendChild(txt);
      bar.appendChild(ind);
    }
    return ind;
  }
  function render() {
    var ind = indicator(); if (!ind || !updatedAt) return;
    var age = Date.now() - updatedAt.getTime();
    var stale = isFinite(STALE_MS[cadence]) && age > STALE_MS[cadence];
    var label = "Updated " + fmtClock(updatedAt);
    ind.classList.remove("stale", "closed", "asof");
    if (cadence === "static-study") {
      ind.classList.add("asof"); label += " · Study, as of its last run";
    } else if (cadence === "intraday-minutes" && !etNow().marketOpen) {
      ind.classList.add("closed"); label += " · Market closed";
    } else if (stale) {
      ind.classList.add("stale"); label += " · Stale";
    }
    ind.querySelector(".livetext").textContent = label;
    ind.setAttribute("data-updated-iso", updatedAt.toISOString());
    ind.setAttribute("data-cadence", cadence);
  }
  function hash(text) {
    var h = 5381;
    for (var i = 0; i < text.length; i++) h = ((h << 5) + h + text.charCodeAt(i)) | 0;
    return text.length + ":" + (h >>> 0).toString(16);
  }
  function check() {
    var url = dataUrl + (dataUrl.indexOf("?") >= 0 ? "&" : "?") + "live=" + Date.now();
    return fetch(url, { cache: "no-store" }).then(function (r) {
      if (!r.ok) return null;
      var lm = r.headers.get("Last-Modified");
      return r.text().then(function (text) {
        return { fp: (lm || "") + "|" + hash(text),
                 at: lm ? new Date(lm) : null, text: text };
      });
    }).catch(function () { return null; }).then(function (res) {
      if (!res) return false;
      if (fingerprint === null) {
        fingerprint = res.fp; updatedAt = res.at || new Date(); render();
        return false;
      }
      if (res.fp !== fingerprint) {
        fingerprint = res.fp; updatedAt = res.at || new Date(); updates++;
        render();
        document.dispatchEvent(new CustomEvent("terminal-data-updated",
          { detail: { slug: slug, cadence: cadence, updates: updates } }));
        if (typeof window.__pageChartsRerender === "function") {
          try { window.__pageChartsRerender(); } catch (e) {}
        }
        if (typeof window.__explanationRerender === "function") {
          try { window.__explanationRerender(); } catch (e) {}
        }
        return true;
      }
      render();
      return false;
    });
  }
  window.__terminalLive = { slug: slug, cadence: cadence, pollMs: pollMs,
    checkNow: check,
    get updates() { return updates; },
    get updatedAt() { return updatedAt; } };
  function start() {
    check();
    if (pollMs > 0) setInterval(check, pollMs);
    setInterval(render, 30000); // stale state is honest even between polls
    document.addEventListener("visibilitychange", function () {
      if (!document.hidden) check();
    });
  }
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", start);
  else start();
})();
"""


def cadence_map() -> dict:
    rows = {}
    for line in INFO_MAP.read_text(encoding="utf-8").splitlines():
        if not line.startswith("|"):
            continue
        parts = [p.strip() for p in line.strip().strip("|").split("|")]
        if len(parts) >= 8 and parts[-1] in KNOWN and re.fullmatch(
                r"[a-z0-9][a-z0-9\-]*", parts[0]):
            rows[parts[0]] = parts[-1]
    return rows


def main() -> int:
    rows = cadence_map()
    if len(rows) != 102:
        print(f"FAIL: INFO-MAP cadence rows = {len(rows)}, expected 102")
        return 1
    nodata = {slug: True for slug in rows
              if not (HERE / slug / "data.json").exists()}
    out = TEMPLATE.replace("__CADENCE__", json.dumps(rows, indent=1,
                                                     sort_keys=True))
    out = out.replace("__NODATA__", json.dumps(nodata, sort_keys=True))
    (HERE / "live.js").write_text(out, encoding="utf-8")
    from collections import Counter
    print(f"live.js generated: {len(rows)} pages, "
          f"{dict(Counter(rows.values()))}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
