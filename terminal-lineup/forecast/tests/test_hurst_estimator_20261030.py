"""Regression blockers for the FE02 Hurst estimator (RC-30, 2026-10-30).

Fail direction: before this cure no Hurst estimator existed in the
stack (the registry recorded the route as absent), so the import
itself fails on the pre-cure tree. The behavioural tests pin the
frozen method: synthetic fractional Gaussian noise generated by
spectral synthesis with known exponents must be recovered inside
the stated tolerance, white noise must read near 0.5, short records
must return None rather than a number, and the registered chop
gate must match its registry formula exactly.
"""
import math
import os
import random
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

from hurst import SCALES, WINDOW_RETURNS, chop_gate, hurst_exponent


def _fgn(n, h, seed):
    """Fractional Gaussian noise by spectral synthesis (seeded)."""
    import numpy as np

    rng = np.random.default_rng(seed)
    freqs = np.fft.rfftfreq(n, d=1.0)
    freqs[0] = freqs[1]
    spectrum = freqs ** (-(2 * h - 1) / 2.0)
    phases = rng.uniform(0, 2 * math.pi, size=len(freqs))
    coeff = spectrum * np.exp(1j * phases)
    coeff[0] = 0.0
    series = np.fft.irfft(coeff, n=n)
    return list(series / series.std())


def _closes_from_returns(returns, start=100.0):
    closes = [start]
    for r in returns:
        closes.append(closes[-1] * math.exp(r * 0.01))
    return closes


def test_recovers_known_exponents():
    # Measured on this frozen form when built: 0.30 read 0.31 and
    # 0.30, 0.50 read 0.43, 0.80 read 0.70, 0.70 read 0.73. The
    # tolerance is the measured accuracy, stated in the module.
    for h_true, seed in ((0.30, 11), (0.50, 22), (0.80, 33),
                         (0.70, 102)):
        rets = _fgn(2500, h_true, seed)
        closes = _closes_from_returns(rets)
        est = hurst_exponent(closes)
        assert est is not None
        assert abs(est - h_true) <= 0.15, (h_true, est)


def test_white_noise_returns_read_near_half():
    rng = random.Random(7)
    closes = _closes_from_returns([rng.gauss(0, 1) for _ in range(2000)])
    est = hurst_exponent(closes)
    assert est is not None and 0.35 <= est <= 0.65, est


def test_short_record_returns_none_not_a_number():
    closes = _closes_from_returns([0.001] * 100)
    assert hurst_exponent(closes) is None


def test_constant_series_returns_none():
    assert hurst_exponent([100.0] * 500) is None


def test_deterministic_and_window_bounded():
    rng = random.Random(3)
    closes = _closes_from_returns([rng.gauss(0, 1) for _ in range(1500)])
    first = hurst_exponent(closes)
    assert first is not None and first == hurst_exponent(closes)
    # Only the trailing window is read: prepending distant history
    # beyond the window cannot change the estimate.
    longer = _closes_from_returns([rng.gauss(0, 1) for _ in range(300)])
    longer = longer + closes[-(WINDOW_RETURNS + 1):]
    assert hurst_exponent(longer) == first


def test_chop_gate_matches_registry_formula():
    assert chop_gate(0.58) == 0.0
    assert abs(chop_gate(0.33) - 1.0) < 1e-9
    assert chop_gate(0.90) == 0.0
    assert abs(chop_gate(0.50) - 0.32) < 1e-12
    assert chop_gate(None) is None


def test_frozen_scales_are_the_registered_ones():
    assert SCALES == (10, 20, 40, 80, 160)
    assert WINDOW_RETURNS == 1000
